// Renders media/sqlsure-intro.mp4 (1920x1080, 30 fps, H.264) from index.html.
//
//   node media/intro/render.ts            capture real tsc output, then render every frame
//   node media/intro/render.ts --frames 3,9.5,20   only write PNG stills at those seconds
//
// Step 1 runs the real tsc --runExternalCode over demo/ (and over demo/ with a column dropped) and
// writes content.js, so the video shows sqlsure's actual output. The numbers come from
// evals/scorecard.json. Step 2 drives headless Chrome over the DevTools protocol (a pipe, no extra
// dependencies), calls setTime(t) for each frame, and pipes the screenshots into ffmpeg.
// Needs google-chrome (or CHROME=path) and ffmpeg on PATH.
import { execFileSync, spawn } from "node:child_process";
import { mkdirSync, readFileSync, rmSync, writeFileSync } from "node:fs";
import { join } from "node:path";
import { pathToFileURL } from "node:url";
import { ensureSelfLink } from "../../evals/lib/tsc.ts";

const ROOT = new URL("../..", import.meta.url).pathname;
const HERE = new URL(".", import.meta.url).pathname;
const DEMO = join(HERE, "demo");
const OUT = join(ROOT, "media/sqlsure-intro.mp4");
const FPS = 30;

function tscIn(dir: string, pretty: boolean): string {
  ensureSelfLink();
  const args = ["-p", ".", "--noEmit", "--runExternalCode", `--pretty`, String(pretty)];
  try {
    return execFileSync(join(ROOT, "node_modules/.bin/tsc"), args, { cwd: dir, encoding: "utf8", stdio: ["ignore", "pipe", "pipe"] });
  } catch (e) {
    const err = e as { stdout?: string; stderr?: string };
    return `${err.stdout ?? ""}${err.stderr ?? ""}`;
  }
}

function capture(): void {
  const read = (p: string) => readFileSync(join(DEMO, p), "utf8").trimEnd();
  const schemaSql = read("db/schema.sql");
  const droppedLine = "  display_name text,";

  // The demo compiles cleanly as written.
  const clean = tscIn(DEMO, false);
  if (clean.trim()) throw new Error(`demo/ should type-check cleanly:\n${clean}`);

  // The type of `user`, as tsc prints it in an error.
  const reveal = join(DEMO, "src/__reveal.ts");
  writeFileSync(reveal, `import { getUser } from "./users.sql";\ndeclare const pool: import("pg").Pool;\nconst user = await getUser(pool, { id: 42 });\nconst probe: never = user;\nexport {};\n`);
  let revealed: string;
  try {
    revealed = tscIn(DEMO, false);
  } finally {
    rmSync(reveal);
  }
  const type = /Type '(.*)' is not assignable to type 'never'/.exec(revealed)?.[1];
  if (!type) throw new Error(`could not read the type of user:\n${revealed}`);
  const m = /^\{ (.*); \} \| null$/.exec(type);
  if (!m) throw new Error(`unexpected type shape: ${type}`);
  const hoverType = `const user: {\n${m[1].split("; ").map((f) => `    ${f};`).join("\n")}\n} | null`;

  // Drop the column and keep tsc's own report.
  const schemaPath = join(DEMO, "db/schema.sql");
  const original = readFileSync(schemaPath, "utf8");
  writeFileSync(schemaPath, original.replace(`${droppedLine}\n`, ""));
  let broken: string;
  try {
    broken = tscIn(DEMO, true);
  } finally {
    writeFileSync(schemaPath, original);
  }
  // Strip ANSI colors and the blank line tsc prints between blocks; the page colors it itself.
  const tscOutput = broken.replace(/\x1b\[[0-9;]*m/g, "").replace(/\n{2,}/g, "\n").trim();
  if (!tscOutput.includes('column "display_name" does not exist')) throw new Error(`unexpected tsc output:\n${broken}`);

  const card = JSON.parse(readFileSync(join(ROOT, "evals/scorecard.json"), "utf8"));
  const killed = card.mutations.filter((x: { killed: boolean }) => x.killed).length;
  const fmt = (n: number) => Math.round(n).toLocaleString("en-US");
  const content = {
    tagline1: "Import .sql files in TypeScript.",
    tagline2: "Get types Postgres itself vouches for.",
    usersSql: read("src/users.sql"),
    appTs: read("src/app.ts"),
    schemaSql,
    droppedLine,
    command: "tsc --noEmit --runExternalCode",
    tscOutput,
    hoverType,
    evidence: [
      {
        to: card.soundness.violations.length,
        label: "values contradicting their type",
        detail: `${fmt(card.soundness.valuesChecked)} values from ${fmt(card.soundness.queriesExecuted)} queries, checked on real Postgres`,
      },
      {
        to: card.breadth.percent,
        decimals: 1,
        suffix: "%",
        label: "of sqlc's real-world test queries typed",
        detail: `${card.breadth.typed} of ${card.breadth.acceptedByPostgres} queries written by other people`,
      },
      {
        to: killed,
        suffix: `/${card.mutations.length}`,
        label: "deliberately injected bugs caught",
        detail: "mutation testing proves the checks can fail",
      },
    ],
  };
  const js = `// Generated by render.ts from a real tsc run and evals/scorecard.json. Do not edit.
window.CONTENT = ${JSON.stringify(content, null, 2)};
for (const r of window.CONTENT.evidence) r.count = (p) => (r.to * p).toFixed(r.decimals ?? 0) + (r.suffix ?? "");
`;
  writeFileSync(join(HERE, "content.js"), js);
  console.log("captured content.js");
}

/** Chrome DevTools protocol over --remote-debugging-pipe: NUL-separated JSON on fds 3 and 4. */
async function chrome() {
  const bin = process.env.CHROME ?? "google-chrome";
  const userDir = join(ROOT, "media/.chrome-profile");
  const proc = spawn(bin, ["--headless=new", "--remote-debugging-pipe", "--hide-scrollbars", "--force-color-profile=srgb", "--allow-file-access-from-files", "--no-first-run", "--disable-gpu", `--user-data-dir=${userDir}`, "about:blank"], {
    stdio: ["ignore", "ignore", "ignore", "pipe", "pipe"],
  });
  const write = proc.stdio[3] as NodeJS.WritableStream;
  const read = proc.stdio[4] as NodeJS.ReadableStream;
  let id = 0;
  const pending = new Map<number, { resolve: (v: any) => void; reject: (e: Error) => void }>();
  let buf = "";
  read.on("data", (chunk: Buffer) => {
    buf += chunk.toString("utf8");
    let end: number;
    while ((end = buf.indexOf("\0")) !== -1) {
      const msg = JSON.parse(buf.slice(0, end));
      buf = buf.slice(end + 1);
      const p = msg.id !== undefined ? pending.get(msg.id) : undefined;
      if (p) {
        pending.delete(msg.id);
        msg.error ? p.reject(new Error(JSON.stringify(msg.error))) : p.resolve(msg.result);
      }
    }
  });
  const send = (method: string, params: object = {}, sessionId?: string): Promise<any> =>
    new Promise((resolve, reject) => {
      const msgId = ++id;
      pending.set(msgId, { resolve, reject });
      write.write(JSON.stringify({ id: msgId, method, params, ...(sessionId ? { sessionId } : {}) }) + "\0");
    });
  const { targetId } = await send("Target.createTarget", { url: "about:blank" });
  const { sessionId } = await send("Target.attachToTarget", { targetId, flatten: true });
  const page = (method: string, params: object = {}) => send(method, params, sessionId);
  await page("Emulation.setDeviceMetricsOverride", { width: 1920, height: 1080, deviceScaleFactor: 1, mobile: false });
  await page("Page.enable");
  return {
    page,
    close: () => {
      proc.kill();
      rmSync(userDir, { recursive: true, force: true });
    },
  };
}

async function evaluate(page: (m: string, p?: object) => Promise<any>, expression: string): Promise<any> {
  const r = await page("Runtime.evaluate", { expression, awaitPromise: true, returnByValue: true });
  if (r.exceptionDetails) throw new Error(`page error: ${JSON.stringify(r.exceptionDetails)}`);
  return r.result.value;
}

async function render(stills: number[] | null): Promise<void> {
  const { page, close } = await chrome();
  try {
    await page("Page.navigate", { url: pathToFileURL(join(HERE, "index.html")).href });
    for (let i = 0; i < 50 && (await evaluate(page, "typeof window.setTime")) !== "function"; i++) await new Promise((r) => setTimeout(r, 100));
    const fonts = await evaluate(page, `document.fonts.ready.then(() => ["800 20px Inter", "400 20px JBM"].every((f) => document.fonts.check(f)))`);
    if (!fonts) throw new Error("fonts did not load");
    const duration: number = await evaluate(page, "window.DURATION");
    const shot = async (t: number): Promise<Buffer> => {
      await evaluate(page, `window.setTime(${t})`);
      const { data } = await page("Page.captureScreenshot", { format: "png" });
      return Buffer.from(data, "base64");
    };

    if (stills) {
      const dir = join(ROOT, "media/stills");
      mkdirSync(dir, { recursive: true });
      for (const t of stills) writeFileSync(join(dir, `t${t.toFixed(2)}.png`), await shot(t));
      console.log(`wrote ${stills.length} stills to media/stills`);
      return;
    }

    const ffmpeg = spawn("ffmpeg", [
      "-y", "-loglevel", "error",
      "-f", "image2pipe", "-framerate", String(FPS), "-i", "-",
      "-f", "lavfi", "-i", "anullsrc=channel_layout=stereo:sample_rate=48000",
      "-shortest", "-map", "0:v", "-map", "1:a",
      "-c:v", "libx264", "-profile:v", "high", "-preset", "slow", "-crf", "16", "-pix_fmt", "yuv420p", "-r", String(FPS),
      "-c:a", "aac", "-b:a", "128k",
      "-movflags", "+faststart",
      OUT,
    ], { stdio: ["pipe", "inherit", "inherit"] });
    const done = new Promise<void>((resolve, reject) => ffmpeg.on("close", (code) => (code === 0 ? resolve() : reject(new Error(`ffmpeg exited ${code}`)))));
    const frames = Math.round(duration * FPS);
    for (let f = 0; f < frames; f++) {
      const png = await shot(f / FPS);
      if (!ffmpeg.stdin.write(png)) await new Promise((r) => ffmpeg.stdin.once("drain", r));
      if (f % (FPS * 5) === 0) console.log(`frame ${f}/${frames}`);
    }
    ffmpeg.stdin.end();
    await done;
    console.log(`wrote ${OUT}`);
  } finally {
    close();
  }
}

const framesArg = process.argv.indexOf("--frames");
const stills = framesArg !== -1 ? process.argv[framesArg + 1].split(",").map(Number) : null;
capture();
await render(stills);
